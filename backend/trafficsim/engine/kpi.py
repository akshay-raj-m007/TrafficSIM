"""Measured KPIs. Every number is computed from simulation state, none is estimated.

flow      detector-line crossings (engine/detectors.py), last 60 s, scaled to veh/h
queue     unbroken chains of queued vehicles at stop lines (engine/queues.py)
delay     per exited vehicle (t_exit − t_ins) − free-flow time of the same route and
          class, the latter measured by the same engine (engine/freeflow.py); entry-queue
          wait t_ins − t_gen is reported separately
unserved  vehicles waiting in entry queues (blocked spawns), cumulative counters
signal    the controller's actual state
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass

from trafficsim.engine.detectors import Detectors, DetectorSpec
from trafficsim.engine.freeflow import DelayReference, reference_for
from trafficsim.engine.laneflow import LaneFlow
from trafficsim.engine.params.control import (
    DETECTOR_WINDOW_S,
    KPI_RECENT_WINDOW_S,
)
from trafficsim.engine.queues import QUEUE_MAX_GAP_M, ApproachSpec, QueueMeter

KPI_DEFS: dict[str, str] = {
    "flow": "Vehicles whose front crossed the detector line in the last 60 s (any lane), "
    "scaled to veh/h. One vehicle = 60 veh/h. Counted from simulation positions.",
    "queue": "Unbroken chain of vehicles slower than 2.2 m/s (HCM 5 mi/h) starting at the "
    f"stop line, each within {QUEUE_MAX_GAP_M:.1f} m of the one ahead. Length = stop line "
    "to the rear of the last queued vehicle; longest lane of the approach.",
    "delay": "Mean over vehicles that left the network of (actual travel time - free-flow "
    "travel time of the same route and class). Free-flow time is measured by running one "
    "vehicle alone on the empty network in this same model. Entry-queue wait is separate.",
    "unserved": "Vehicles generated by the demand process that are still waiting to enter "
    "because the entry lane had no safe gap (never dropped).",
    "signal": "Current state of the J1 signal controller.",
    "lane_flow": "Vehicles that arrived on each lane or junction connector in the last 5 min "
    "(by insertion, transfer or lane change), scaled to veh/h; one entry per frame segment.",
}


@dataclass(frozen=True, slots=True)
class KpiLayout:
    detectors: tuple[DetectorSpec, ...]
    approaches: tuple[ApproachSpec, ...]


class KpiHub:
    def __init__(self, sim, layout: KpiLayout | None) -> None:
        self.sim = sim
        self.lane_flow = LaneFlow(sim.lg.n)
        self.detectors = Detectors(sim.lg, layout.detectors) if layout else None
        self.queues = QueueMeter(sim.lg, layout.approaches) if layout else None
        self._q_hist: deque[tuple[float, list[float]]] = deque()
        self._exit_ptr = 0
        self._pending: list = []
        self._n = 0
        self._sum = 0.0
        self._wait_sum = 0.0
        self._recent: deque[tuple[float, float]] = deque()  # (t_exit, delay)
        self.ref = None
        if layout:  # the free-flow reference is only needed when delay is reported
            self.ref = reference_for(sim.network, sim.lg)
            self.delay_ref = DelayReference(sim.network, self.ref)
            self.request_reference()

    def request_reference(self) -> None:
        """Ask for the free-flow time of every origin-destination pair in use (open network)."""
        if self.ref:
            sim = self.sim
            pairs = dict.fromkeys(p for p in sim.routes.pair if p != ("", ""))
            self.ref.request(
                [(self.delay_ref.roads(p), c) for p in pairs for c in sim.demand.class_indices()]
            )

    # ------------------------------------------------------------- per step
    def observe(self, vs, s_before, t_now: float) -> None:
        if self.detectors:
            self.detectors.observe(vs, s_before, t_now)

    def observe_segments(self, vs, tick: int) -> None:
        self.lane_flow.observe(vs, tick)  # after the transfers: where each vehicle now is

    def sample(self, t_now: float) -> None:
        if not self.queues:
            return
        self._q_hist.append((t_now, [q[1] for q in self.queues.measure(self.sim.vehicles)]))
        while self._q_hist and self._q_hist[0][0] <= t_now - DETECTOR_WINDOW_S:
            self._q_hist.popleft()

    # ------------------------------------------------------------- snapshot
    def _update_delays(self) -> None:
        sim = self.sim
        exits = sim.log.exits
        waiting = self._pending + exits[self._exit_ptr :]
        self._exit_ptr = len(exits)
        self._pending = []
        for e in waiting:
            ff = self.delay_ref.free_flow(sim.routes.pair[e.route], e.cls) if self.ref else None
            if ff is None:
                self._pending.append(e)
                continue
            d = (e.t_exit - e.t_ins) - ff
            self._n += 1
            self._sum += d
            self._wait_sum += e.t_ins - e.t_gen
            self._recent.append((e.t_exit, d))
        t = sim.time_s
        while self._recent and self._recent[0][0] <= t - KPI_RECENT_WINDOW_S:
            self._recent.popleft()

    def snapshot(self) -> dict:
        sim = self.sim
        t = sim.time_s
        d = sim.demand
        out: dict = {
            "t": round(t, 1),
            "tick": sim.tick,
            "counts": {
                "generated": d.generated, "inserted": d.inserted, "exited": sim.exited,
                "active": sim.active, "queued": d.queued,
            },
            "signal": self._signal(),
            "lane_flow": self.lane_flow.veh_per_h(t),
        }  # fmt: skip
        if self.detectors:
            out["flow"] = [
                {
                    "id": sp.id, "label": sp.label,
                    "veh_per_h": round(self.detectors.flow_veh_per_h(k, t)),
                    "in_window": self.detectors.window_count(k, t),
                    "total": int(self.detectors.total[k]),
                }
                for k, sp in enumerate(self.detectors.specs)
            ]  # fmt: skip
            now = self.queues.measure(sim.vehicles)
            hist = [lens for _, lens in self._q_hist]
            out["queues"] = [
                {
                    "id": sp.id, "label": sp.label, "veh": n, "length_m": round(length, 1),
                    "max_window_m": round(max([length] + [h[i] for h in hist]), 1),
                }
                for i, (sp, (n, length)) in enumerate(zip(self.queues.specs, now, strict=True))
            ]  # fmt: skip
            self._update_delays()
            recent = [x for _, x in self._recent]
            out["delay"] = {
                "reference_ready": not self._pending, "n": self._n,
                "mean_s": round(self._sum / self._n, 2) if self._n else None,
                "recent_n": len(recent),
                "recent_mean_s": round(sum(recent) / len(recent), 2) if recent else None,
                "entry_wait_mean_s": round(self._wait_sum / self._n, 2) if self._n else None,
            }  # fmt: skip
        by_zone = d.queued_by_zone()
        zone_of = {z.entry_road: z.id for z in sim.network.zones}
        oldest = max((t - z.queue[0].t_gen for z in d.zones if z.queue), default=0.0)
        out["unserved"] = {
            "queued": d.queued, "oldest_wait_s": round(oldest, 1),
            "by_zone": {zone_of[r]: n for r, n in by_zone.items()},
        }  # fmt: skip
        return out

    def _signal(self) -> dict | None:
        sim = self.sim
        if not sim.signals:
            return None
        c = sim.signals[0]
        out = {
            "junction": c.junction_id, "controller": c.name, "phase": c.phase,
            "approach": c.phases[c.phase].approach_road, "state": c.state,
            "elapsed_s": round(c.elapsed / 10.0, 1), "n_phases": len(c.phases),
        }  # fmt: skip
        if hasattr(c, "plan"):
            out["cycle_s"] = round(c.plan.cycle_s, 1)
        return out
